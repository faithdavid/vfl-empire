# ─── Main ───────────────────────────────────────────────────────────────────


def main() -> None:
    ledger = load_ledger()
    bankroll = ledger.get("bankroll", {}).get("current", 100.0)

    print(f"💰 **VFL Auto-Bet Agent**")
    print(f"   Bankroll: {bankroll:.2f}u")
    print()

    # 1. Fetch current state
    info = get_current_match_day_info()
    if info:
        print(f"   Season: {info.get('seasonName')} | MD{info.get('matchDay')} ({info.get('status')})")
    print()

    # 2. Load unpicked bets from LLM predictor
    llm_picks = load_llm_picks()
    print(f"📥 Pending LLM picks: {len(llm_picks)}")

    if not llm_picks:
        print("✅ No pending picks to place")
        # Still check rapid scanner picks
        return

    # 3. Verify each pick against live odds
    verified_picks = []
    for pick in llm_picks:
        print(f"🔍 Verifying: {pick.get('home')} vs {pick.get('away')} — {pick.get('selection')} @{pick.get('odds')}")

        verified = verify_pick_with_live_odds(pick)
        if verified:
            if float(verified.get("odds", 0)) <= 0:
                print(f"   ❌ Selection no longer available")
                continue
            print(f"   ✅ Verified — odds still valid @{verified.get('odds')}")
            verified_picks.append(verified)
        else:
            print(f"   ❌ Event not found or expired")
            # Mark as expired
            pick["expired"] = True

    if not verified_picks:
        print("\n😴 No verified picks to bet on")
        return

    # 4. Calculate stakes and place bets
    print(f"\n📊 **Placing {len(verified_picks)} bet(s)**")
    print()

    placed_count = 0
    total_stake = 0.0

    for pick in verified_picks:
        stake = calculate_stake(pick)

        # Check bankroll
        if stake > bankroll:
            print(f"   ⛔ Insufficient bankroll for {pick['home']} vs {pick['away']}")
            continue

        print(f"🎯 {pick['home']} vs {pick['away']}")
        print(f"   Selection: {pick['selection']} @{pick['odds']}")
        print(f"   Stake: {stake:.2f}u | Confidence: {pick['confidence']}")

        # Place bet
        if USE_API_BETTING:
            success = place_bet_via_api(pick, stake)
        else:
            success = place_bet_via_browser(pick, stake)

        if success:
            placed_count += 1
            total_stake += stake
            bankroll -= stake

            # Mark pick as placed
            pick["placed"] = True
            pick["placed_at"] = datetime.now(timezone.utc).isoformat()
            pick["stake"] = stake

            # Log to ledger
            ledger["bets"].append({
                "pick": pick,
                "stake": stake,
                "placed_at": pick["placed_at"],
                "settled": False,
            })
            ledger["bankroll"]["current"] = round(bankroll, 2)
            save_ledger(ledger)

            print(f"   ✅ Bet placed!")
        else:
            print(f"   ⏳ Bet queued for manual placement")

        print()

    # Summary
    print(f"📈 **Summary:** {placed_count} bet(s) placed | Total stake: {total_stake:.2f}u")
    print(f"💰 **Bankroll remaining:** {bankroll:.2f}u")

    # Save updated picks (mark them as placed/verified)
    try:
        if os.path.exists(Llm_PICKS_FILE):
            with open(Llm_PICKS_FILE) as f:
                existing = json.load(f)
        else:
            existing = []

        # Update old picks with new state
        verified_ids = {vp.get("id") for vp in verified_picks}
        updated = []
        for old in existing:
            if old.get("id") in verified_ids:
                # Find the matching verified pick
                match = next((vp for vp in verified_picks if vp.get("id") == old.get("id")), old)
                updated.append(match)
            else:
                updated.append(old)
        # Add any new verified picks not in original
        for vp in verified_picks:
            if vp.get("id") not in {o.get("id") for o in existing}:
                updated.append(vp)

        with open(Llm_PICKS_FILE, "w") as f:
            json.dump(updated, f, indent=2)
    except Exception as e:
        logger.warning("Failed to save picks: %s", e)


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"[ERROR] auto_bet failed: {e}", file=sys.stderr)
        sys.exit(1)
