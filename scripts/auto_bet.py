# ─── Pick verification ──────────────────────────────────────────────────────


def verify_pick_with_live_odds(pick: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """
    Verify a pick's odds are still available (not expired/changed).
    Fetches fresh data from the API and confirms the selection still exists.
    Returns updated pick dict with current odds, or None if unavailable.
    """
    event_id = pick.get("event_id")
    if not event_id:
        return None

    match_days = get_event_list()
    if not match_days:
        return None

    # Find event by ID
    for md in match_days:
        for event in md.get("events", []):
            if event.get("eventId") == event_id:
                # Found the event — check market
                market = pick.get("market", "")
                selection = pick.get("selection", "")

                if "Under 3.5" in selection:
                    ou = extract_over_under_odds(event)
                    total_35 = ou.get("total=3.5", {})
                    current_odds = total_35.get("Under 3.5", 0.0)
                    if current_odds > 0:
                        updated = dict(pick)
                        updated["current_odds"] = current_odds
                        updated["odds"] = f"{current_odds:.2f}"
                        return updated
                elif selection == "Home":
                    odds_1x2 = extract_1x2_odds(event)
                    if odds_1x2.get("Home", 0) > 0:
                        updated = dict(pick)
                        updated["current_odds"] = odds_1x2["Home"]
                        updated["odds"] = f'{odds_1x2["Home"]:.2f}'
                        return updated
                elif selection == "Away":
                    odds_1x2 = extract_1x2_odds(event)
                    if odds_1x2.get("Away", 0) > 0:
                        updated = dict(pick)
                        updated["current_odds"] = odds_1x2["Away"]
                        updated["odds"] = f'{odds_1x2["Away"]:.2f}'
                        return updated

                # Event found but market/selection not available
                return None

    return None


# ─── Stake calculation ──────────────────────────────────────────────────────


def calculate_stake(pick: Dict[str, Any]) -> float:
    """
    Calculate stake based on confidence and odds.
    Kelly Criterion-inspired: f* = (bp - q) / b
    where b = decimal odds - 1, p = win probability, q = 1-p
    """
    confidence_str = pick.get("confidence", "90%")
    try:
        confidence = float(confidence_str.rstrip("%")) / 100.0
    except (ValueError, AttributeError):
        confidence = 0.85

    odds = float(pick.get("odds", 0))
    if odds <= 1.0:
        return DEFAULT_STAKE

    b = odds - 1
    q = 1 - confidence

    # Kelly fraction
    kelly = (b * confidence - q) / b if b > 0 else 0

    # Conservative: use 25% Kelly
    stake = kelly * 0.25 * 100  # Scale to units

    # Clamp
    stake = max(DEFAULT_STAKE, min(MAX_STAKE, stake))
    return round(stake, 2)


